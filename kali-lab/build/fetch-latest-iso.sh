#!/usr/bin/env bash
#
# fetch-latest-iso.sh — resolve the CURRENT Kali installer ISO (name + SHA256)
# straight from Kali's published SHA256SUMS, and write them to a Packer vars file
# that overrides the pinned defaults in kali.pkr.hcl.
#
# Packer auto-loads any *.auto.pkrvars.hcl in the build dir, so after running
# this you can just `packer build .` (or `make bake`) with no -var and no edits.
#
# Usage:
#   ./fetch-latest-iso.sh                 # installer-amd64 (default)
#   VARIANT=installer-netinst ./fetch-latest-iso.sh
#   VARIANT=installer-everything ./fetch-latest-iso.sh
#   ARCH=amd64 BASE_URL=https://cdimage.kali.org/current ./fetch-latest-iso.sh
#
# Env vars:
#   VARIANT   ISO flavour token as it appears in the filename between the version
#             and the arch. Default: installer.
#             Common: installer | installer-netinst | installer-everything | live
#   ARCH      Default: amd64
#   BASE_URL  Where the ISO + SHA256SUMS live. Default: Kali /current (redirects
#             to the latest release). Follows redirects automatically.
#   OUT       Output vars file. Default: iso.auto.pkrvars.hcl next to this script.

set -euo pipefail

VARIANT="${VARIANT:-installer}"
ARCH="${ARCH:-amd64}"
BASE_URL="${BASE_URL:-https://cdimage.kali.org/current}"
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="${OUT:-$SCRIPT_DIR/iso.auto.pkrvars.hcl}"

# --- pick a downloader -------------------------------------------------------
if command -v curl >/dev/null 2>&1; then
  dl() { curl -fsSL "$1"; }
elif command -v wget >/dev/null 2>&1; then
  dl() { wget -qO- "$1"; }
else
  echo "!! need curl or wget on PATH" >&2
  exit 1
fi

echo ">> Fetching ${BASE_URL}/SHA256SUMS"
SUMS="$(dl "${BASE_URL}/SHA256SUMS")"

# --- match the wanted ISO line: '<64-hex>␠␠<filename>' ------------------------
# Filename shape: kali-linux-<version>-<VARIANT>-<ARCH>.iso
pattern="kali-linux-[^ ]*-${VARIANT}-${ARCH}\.iso"
line="$(printf '%s\n' "$SUMS" | grep -E "  ${pattern}\$" | head -1 || true)"

if [[ -z "$line" ]]; then
  echo "!! no ISO matching VARIANT='${VARIANT}' ARCH='${ARCH}' in SHA256SUMS." >&2
  echo "   Available amd64 ISOs:" >&2
  printf '%s\n' "$SUMS" | grep -Eo "kali-linux-[^ ]*-${ARCH}\.iso" | sort -u | sed 's/^/     - /' >&2
  exit 1
fi

hash="$(awk '{print $1}' <<<"$line")"
filename="$(awk '{print $NF}' <<<"$line")"

# --- sanity: hash must be 64 hex chars ---------------------------------------
if ! [[ "$hash" =~ ^[0-9a-f]{64}$ ]]; then
  echo "!! parsed hash does not look like sha256: '$hash'" >&2
  exit 1
fi

iso_url="${BASE_URL}/${filename}"

# --- write the Packer auto-vars file -----------------------------------------
cat > "$OUT" <<EOF
# AUTO-GENERATED by fetch-latest-iso.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Do not edit by hand — re-run the script to refresh.
iso_url      = "${iso_url}"
iso_checksum = "sha256:${hash}"
EOF

echo ">> Resolved: ${filename}"
echo ">> SHA256  : ${hash}"
echo ">> Wrote   : ${OUT}"
echo ">> Packer will auto-load it; run 'packer build .' or 'make bake'."
